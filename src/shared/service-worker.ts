import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

/**
 * The service worker of the installable app (PWA), written into every production build as `sw.js`.
 *
 * - Precaches the app shell: every file Vite emitted plus the public files the app needs to start
 *   (fonts, icons, the manifest, the intro script). Plan, Freestyle and Experience are built-in, so
 *   with the shell cached they work offline; music always comes from the network (or not at all).
 * - Never touches other origins (YouTube, Spotify, GetSongBPM...), `api/` (the local server's
 *   data), the help pages or the opt-in Deezer bridge. It never reads or writes IndexedDB or
 *   localStorage: the rider's data stays exactly as it was.
 * - Pages: network first, the cached `index.html` when offline. Files: cache first (they are
 *   content-hashed or listed in the precache), filled on the way.
 * - A new version waits until the page asks it to take over (the "new version" notice), so an
 *   open ride is never swapped under the rider. The very first install takes over at once.
 */
export function serviceWorkerSource(precache: readonly string[], version: string): string {
  return `/* HyperCycling service worker ${version}. Generated by src/shared/service-worker.ts. */
const CACHE = 'hc-${version}';
const PRECACHE = ${JSON.stringify(precache)};
const BYPASS = /^(api\\/|docs\\/|deezer-bridge\\.)/;

const scope = () => new URL(self.registration.scope);
const local = (url) => {
  const s = scope();
  return url.origin === s.origin && url.pathname.startsWith(s.pathname)
    ? url.pathname.slice(s.pathname.length)
    : null;
};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((p) => new URL(p, scope()).href)))
      .then(() => (self.registration.active ? undefined : self.skipWaiting())),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'hc-skip-waiting') self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('hc-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  const rel = local(url);
  if (rel === null || BYPASS.test(rel)) return;
  const index = new URL('index.html', scope()).href;
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && (rel === '' || rel === 'index.html')) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(index, copy));
          }
          return response;
        })
        .catch(() => caches.match(index).then((hit) => hit || Response.error())),
    );
    return;
  }
  event.respondWith(
    caches.match(request).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
}

/** Public files the shell needs (relative to the base URL); docs and the Deezer bridge stay out. */
export function publicShellFiles(publicDir: string): string[] {
  const fonts = readdirSync(path.join(publicDir, 'fonts'))
    .filter((f) => f.endsWith('.woff2'))
    .map((f) => `fonts/${f}`);
  return [
    'index.html',
    'manifest.webmanifest',
    'intro-boot.js',
    'favicon.svg',
    'icon-192.png',
    'icon-512.png',
    'icon-maskable-512.png',
    'apple-touch-icon.png',
    ...fonts,
  ];
}

/** Vite plugin: emits `sw.js` with the build's own file list and a version from its hash. */
export function serviceWorkerPlugin(publicDir = 'public'): Plugin {
  return {
    name: 'spinning-tutor:service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const emitted = Object.keys(bundle)
        .filter((f) => f !== 'index.html' && !f.endsWith('.map'))
        .sort();
      const precache = [...new Set([...publicShellFiles(publicDir), ...emitted])];
      // The version follows the content (a changed public file or chunk), not only the names.
      const hash = createHash('sha256').update(precache.join('\n'));
      for (const f of emitted) {
        const out = bundle[f];
        if (out) hash.update(out.type === 'chunk' ? out.code : out.source);
      }
      for (const f of publicShellFiles(publicDir)) {
        if (f === 'index.html') continue;
        try {
          hash.update(readFileSync(path.join(publicDir, f)));
        } catch {
          // a missing public file fails at install time, where it is reported
        }
      }
      const version = hash.digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(precache, version),
      });
    },
  };
}
